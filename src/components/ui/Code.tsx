"use client";
import { useEffect, useState } from "react";
import { Check, Copy, Download } from "lucide-react";

type Lang = "typescript" | "python" | "json" | "bash";

let highlighterPromise: Promise<{ codeToHtml: (code: string, opts: { lang: string; theme: string }) => string }> | null = null;

/** Shiki with the JavaScript regex engine (no WebAssembly, so no 'wasm-unsafe-eval' in the CSP). */
function highlighter() {
  if (!highlighterPromise) {
    highlighterPromise = (async () => {
      const [{ createHighlighterCore }, { createJavaScriptRegexEngine }] = await Promise.all([import("shiki/core"), import("shiki/engine/javascript")]);
      return createHighlighterCore({
        themes: [import("@shikijs/themes/poimandres")],
        langs: [import("@shikijs/langs/typescript"), import("@shikijs/langs/python"), import("@shikijs/langs/json")],
        engine: createJavaScriptRegexEngine(),
      });
    })();
  }
  return highlighterPromise;
}

export function Code({ code, lang, filename, maxHeight = 420 }: { code: string; lang: Lang; filename?: string; maxHeight?: number }) {
  const [html, setHtml] = useState<string | null>(null);
  const [copied, setCopied] = useState(false);
  useEffect(() => {
    let cancelled = false;
    if (lang === "bash") return;
    // Shiki escapes the code it renders; the input here is generated by this app, never raw document HTML.
    void highlighter()
      .then((h) => h.codeToHtml(code, { lang, theme: "poimandres" }))
      .then((out) => !cancelled && setHtml(out))
      .catch(() => setHtml(null));
    return () => {
      cancelled = true;
    };
  }, [code, lang]);

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(code);
      setCopied(true);
      setTimeout(() => setCopied(false), 1400);
    } catch {
      /* clipboard blocked */
    }
  };
  const download = () => {
    if (!filename) return;
    const url = URL.createObjectURL(new Blob([code], { type: "text/plain" }));
    const a = document.createElement("a");
    a.href = url;
    a.download = filename;
    a.click();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  };

  return (
    <div className="overflow-hidden rounded-xl border border-line bg-[#1b1e28]">
      <div className="flex items-center justify-between border-b border-white/5 px-3 py-1.5">
        <span className="font-mono text-[11px] text-ink-3">{filename ?? lang}</span>
        <div className="flex gap-1">
          <button type="button" className="btn btn-ghost btn-xs" onClick={() => void copy()}>
            {copied ? <Check size={12} aria-hidden="true" /> : <Copy size={12} aria-hidden="true" />} {copied ? "Copied" : "Copy"}
          </button>
          {filename && (
            <button type="button" className="btn btn-ghost btn-xs" onClick={download}>
              <Download size={12} aria-hidden="true" /> Download
            </button>
          )}
        </div>
      </div>
      <div className="overflow-auto text-[12px] leading-[1.55] scroll-thin [&_pre]:!bg-transparent [&_pre]:p-3" style={{ maxHeight }}>
        {html ? <div dangerouslySetInnerHTML={{ __html: html }} /> : <pre className="whitespace-pre p-3 font-mono text-[#a6accd]">{code}</pre>}
      </div>
    </div>
  );
}
