/**
 * Synchronous SHA-256 and canonical JSON.
 *
 * The engine hashes rows, transform specs, audit entries and checkpoints in
 * pure functions that run in a Web Worker, in Node (benchmarks, Playwright
 * runner, MCP server) and in tests. Web Crypto is async, so a small, tested,
 * synchronous implementation keeps every node a plain function.
 * Verified against node:crypto in tests/unit/hash.test.ts.
 */

