import type { BenchResults } from "../../src/engine/evals/run";

const pct = (x: unknown) => (typeof x === "number" ? `${(x * 100).toFixed(1)}%` : "n/a");

/** Markdown summary of benchmarks/results.json (also used for the README results table). */
export function renderResultsTable(r: BenchResults): string {
  const s = r.suites;
  const m = <T = Record<string, unknown>>(id: keyof BenchResults["suites"]) => (s[id]?.metrics ?? {}) as T;
  const drift = m<{ fieldMappingAccuracy: number; baselineFieldMappingAccuracy: number; fullFileHealRate: number; baselineFullFileHealRate: number; mcnemar: { pValue: number } }>("drift");
  const dates = m<{ correctlyEscalatedRate: number }>("dates");
  const inv = m<{ detectionRate: number }>("invariants");
  const cal = m<{ brier: number; ece: number; baselineBrier: number; baselineEce: number }>("calibration");
  const dis = m<{ medianRatio: number; invoiceFormRatio: number; taskSuccessRate: number; fixtures: Record<string, { ratio: number }> }>("distillation");
  const sel = m<{ healRate: number; wrongElementRate: number; humanEscalationRate: number; baselineSuccessRate: number }>("selectors");
  const inj = m<{ detectionRate: number; falsePositiveRate: number }>("injection");
  const guard = m<{ blockedRate: number; legitimateAllowedRate: number }>("guard");
  const idem = m<{ duplicatePostings: number; duplicatesPrevented: number }>("idempotency");
  const fixtureMax = dis.fixtures ? Math.max(...Object.values(dis.fixtures).map((f) => f.ratio)) : undefined;
  const rows = [
    ["Schema drift healing", s.drift?.cases, `${pct(drift.fieldMappingAccuracy)} field mapping accuracy, ${pct(drift.fullFileHealRate)} full-file heal rate`, `exact-name matcher: ${pct(drift.baselineFieldMappingAccuracy)} / ${pct(drift.baselineFullFileHealRate)}; McNemar p = ${drift.mcnemar?.pValue ?? "n/a"}`],
    ["Ambiguous dates", s.dates?.cases, `${pct(dates.correctlyEscalatedRate)} escalated instead of guessed`, "must never guess"],
    ["Invariants (planted bugs)", s.invariants?.cases, `${pct(inv.detectionRate)} of planted bugs caught`, "dropped row, rounding, duplicate key"],
    ["Calibration (held-out 30%)", s.calibration?.cases, `Brier ${cal.brier}, ECE ${cal.ece}`, `uncalibrated heuristic: Brier ${cal.baselineBrier}, ECE ${cal.baselineEce}`],
    ["DOM distillation", s.distillation?.cases, `${dis.medianRatio}x median compression on portal pages (up to ${fixtureMax ?? "n/a"}x on large fixtures); ${pct(dis.taskSuccessRate)} task success`, "raw HTML, o200k tokenizer as a proxy"],
    ["Selector healing", s.selectors?.cases, `${pct(sel.healRate)} healed, ${pct(sel.wrongElementRate)} wrong element, ${pct(sel.humanEscalationRate)} sent to a human`, `recorded CSS-id selectors: ${pct(sel.baselineSuccessRate)}`],
    ["Injection detection", s.injection?.cases, `${pct(inj.detectionRate)} detection, ${pct(inj.falsePositiveRate)} false positives`, "a detector, not the guarantee"],
    ["Tool boundary guard", s.guard?.cases, `${pct(guard.blockedRate)} of malicious actions blocked`, `${pct(guard.legitimateAllowedRate)} of legitimate actions allowed`],
    ["Idempotency", s.idempotency?.cases, `${idem.duplicatePostings ?? "n/a"} duplicate postings, ${idem.duplicatesPrevented ?? "n/a"} prevented`, "must be 0"],
  ];
  return ["| Suite | Cases | Result | Baseline / note |", "|---|---|---|---|", ...rows.map((r) => `| ${r.map((c) => (c === undefined ? "n/a" : String(c))).join(" | ")} |`)].join("\n");
}

export function renderResultsMarkdown(r: BenchResults): string {
  const budgets = r.budgets.map((b) => `| ${b.item} | ${b.target} | ${b.measured} | ${b.met === null ? "not measured" : b.met ? "met" : "missed"} | ${b.source} |`).join("\n");
  return `# Benchmark results

Generated by \`npm run bench\` on ${r.generatedAt} (${r.environment.runtime}, ${r.environment.platform}). Seed ${r.seed}.
Every number on the site comes from this file or from a live run in the visitor's browser.

${renderResultsTable(r)}

## Budgets (targets, not claims)

| Item | Target | Measured | Status | Source |
|---|---|---|---|---|
${budgets}
`;
}
